        "    def __init__(self, stopwords=STOPWORDS_ID, length_penalty_power=0.5):\n",
        "        self.stopwords = list(stopwords)\n",
        "        self.power = length_penalty_power\n",
        "        \n",
        "    def clean_sentence(self, sentence):\n",
        "        \"\"\"Membersihkan karakter non-alfanumerik untuk perhitungan TF-IDF.\"\"\"\n",
        "        s = str(sentence).lower()\n",
        "        s = re.sub(r'[^a-z0-9\\s]', ' ', s)\n",
        "        return re.sub(r'\\s+', ' ', s).strip()\n",
        "        \n",
        "    def summarize(self, text, num_sentences=2):\n",
        "        \"\"\"\n",
        "        Mengekstrak k-kalimat paling penting dari artikel berita menggunakan skor TF-IDF.\n",
        "        \n",
        "        Parameters:\n",
        "            text (str): Teks artikel berita lengkap.\n",
        "            num_sentences (int): Jumlah kalimat ringkasan yang diinginkan (default: 2).\n",
        "            \n",
        "        Returns:\n",
        "            summary_text (str): Teks ringkasan ekstraktif berurutan.\n",
        "            ranking_details (list of dict): Rincian kalimat, skor, dan peringkatnya.\n",
        "        \"\"\"\n",
        "        sentences = split_into_sentences(text)\n",
        "        if len(sentences) <= num_sentences:\n",
        "            return text.strip(), [{\"index\": i, \"sentence\": s, \"score\": 1.0} for i, s in enumerate(sentences)]\n",
        "            \n",
        "        # Preprocessing kalimat untuk TF-IDF\n",
        "        cleaned_sentences = [self.clean_sentence(s) for s in sentences]\n",
        "        \n",
        "        # Bangun matriks TF-IDF: tiap kalimat dianggap sebagai 1 dokumen\n",
        "        vectorizer = TfidfVectorizer(\n",
        "            stop_words=self.stopwords,\n",
        "            ngram_range=(1, 2),  # Unigram dan Bigram\n",
        "            sublinear_tf=True\n",
        "        )\n",
        "        \n",
        "        try:\n",
        "            tfidf_matrix = vectorizer.fit_transform(cleaned_sentences)\n",
        "        except ValueError:\n",
        "            # Fallback jika semua kata terbuang oleh stopword\n",
        "            return ' '.join(sentences[:num_sentences]), []\n",
        "            \n",
        "        # Hitung skor agregat TF-IDF per baris kalimat\n",
        "        raw_scores = np.array(tfidf_matrix.sum(axis=1)).flatten()\n",
        "        \n",
        "        # Normalisasi panjang kalimat agar tidak bias pada kalimat yang terlalu panjang\n",
        "        word_lengths = np.array([max(len(s.split()), 1) for s in sentences])\n",
        "        salience_scores = raw_scores / (word_lengths ** self.power)\n",
        "        \n",
        "        # Urutkan berdasarkan skor tertinggi (descending)\n",
        "        ranked_indices = np.argsort(salience_scores)[::-1]\n",
        "        top_k_indices = ranked_indices[:num_sentences]\n",
        "        \n",
        "        # Rekonstruksi kronologis: urutkan kembali sesuai kemunculan di artikel asli\n",
        "        chronological_indices = sorted(top_k_indices)\n",
        "        selected_sentences = [sentences[i] for i in chronological_indices]\n",
        "        \n",
        "        summary_text = ' '.join(selected_sentences)\n",
        "        \n",
        "        ranking_details = [\n",
        "            {\n",
        "                \"original_pos\": i,\n",
        "                \"sentence\": sentences[i],\n",
        "                \"score\": round(float(salience_scores[i]), 4),\n",
        "                \"is_selected\": (i in top_k_indices)\n",
        "            }\n",
        "            for i in range(len(sentences))\n",
        "        ]\n",
        "        \n",
        "        return summary_text, ranking_details\n",
