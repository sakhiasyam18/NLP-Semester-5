cell_13 = {
    "cell_type": "code",
    "execution_count": None,
    "metadata": {},
    "outputs": [],
    "source": [
        "# ==============================================================================\n",
        "# BAGIAN 5.1: FUNGSI PENGHITUNG METRIK ROUGE-1, ROUGE-2, & ROUGE-L\n",
        "# ==============================================================================\n",
        "\n",
        "def compute_rouge(candidate, reference):\n",
        "    \"\"\"\n",
        "    Menghitung skor ROUGE-1, ROUGE-2, dan ROUGE-L secara presisi (Precision, Recall, F1).\n",
        "    \"\"\"\n",
        "    def get_ngrams(tokens, n):\n",
        "        return [tuple(tokens[i:i+n]) for i in range(len(tokens) - n + 1)]\n",
        "        \n",
        "    def lcs(seq1, seq2):\n",
        "        m, n = len(seq1), len(seq2)\n",
        "        dp = [[0]*(n+1) for _ in range(m+1)]\n",
        "        for i in range(1, m+1):\n",
        "            for j in range(1, n+1):\n",
        "                if seq1[i-1] == seq2[j-1]:\n",
        "                    dp[i][j] = dp[i-1][j-1] + 1\n",
        "                else:\n",
        "                    dp[i][j] = max(dp[i-1][j], dp[i][j-1])\n",
        "        return dp[m][n]\n",
        "        \n",
        "    tok_cand = re.findall(r'\\w+', candidate.lower())\n",
        "    tok_ref  = re.findall(r'\\w+', reference.lower())\n",
        "    \n",
        "    # ROUGE-1\n",
        "    c1 = Counter(tok_cand)\n",
        "    r1 = Counter(tok_ref)\n",
        "    overlap_1 = sum((c1 & r1).values())\n",
        "    rec_1 = overlap_1 / max(len(tok_ref), 1)\n",
        "    prec_1 = overlap_1 / max(len(tok_cand), 1)\n",
        "    f1_1 = 2 * (prec_1 * rec_1) / max((prec_1 + rec_1), 1e-8)\n",
        "    \n",
        "    # ROUGE-2\n",
        "    c2 = Counter(get_ngrams(tok_cand, 2))\n",
        "    r2 = Counter(get_ngrams(tok_ref, 2))\n",
        "    overlap_2 = sum((c2 & r2).values())\n",
        "    rec_2 = overlap_2 / max(len(tok_ref) - 1, 1)\n",
        "    prec_2 = overlap_2 / max(len(tok_cand) - 1, 1)\n",
        "    f1_2 = 2 * (prec_2 * rec_2) / max((prec_2 + rec_2), 1e-8)\n",
        "    \n",
        "    # ROUGE-L\n",
        "    lcs_val = lcs(tok_cand, tok_ref)\n",
        "    rec_l = lcs_val / max(len(tok_ref), 1)\n",
        "    prec_l = lcs_val / max(len(tok_cand), 1)\n",
        "    f1_l = 2 * (prec_l * rec_l) / max((prec_l + rec_l), 1e-8)\n",
        "    \n",
        "    return {\n",
        "        \"rouge1_f1\": round(f1_1, 4),\n",
        "        \"rouge2_f1\": round(f1_2, 4),\n",
        "        \"rougeL_f1\": round(f1_l, 4)\n",
        "    }\n",
        "\n",
        "print(\"Fungsi evaluasi ROUGE terverifikasi!\")"
    ]
}

