        "# ==============================================================================\n",
        "# BAGIAN 4.1: IMPLEMENTASI TEXTRANK SUMMARIZER (STARTER TEMPLATE AGUNG)\n",
        "# Pengembang: Agustinus Maria Agung Heriyanto (240535607403)\n",
        "# ==============================================================================\n",
        "\n",
        "class TextRankSummarizer:\n",
        "    \"\"\"\n",
        "    Model Extractive Summarization berbasis TextRank (Graph Cosine Similarity + PageRank).\n",
        "    Penanggung Jawab: Agustinus Maria Agung Heriyanto (240535607403)\n",
        "    \"\"\"\n",
        "    def __init__(self, stopwords=STOPWORDS_ID, damping=0.85, max_iter=200):\n",
        "        self.stopwords = list(stopwords)\n",
        "        self.damping = damping\n",
        "        self.max_iter = max_iter\n",
        "        \n",
        "    def summarize(self, text, num_sentences=2):\n",
        "        sentences = split_into_sentences(text)\n",
        "        if len(sentences) <= num_sentences:\n",
        "            return text.strip(), [{\"index\": i, \"sentence\": s, \"score\": 1.0} for i, s in enumerate(sentences)]\n",
        "            \n",
        "        # 1. Bangun matriks representasi TF-IDF kalimat\n",
        "        vectorizer = TfidfVectorizer(stop_words=self.stopwords)\n",
        "        try:\n",
        "            tfidf_matrix = vectorizer.fit_transform(sentences)\n",
        "        except ValueError:\n",
        "            return ' '.join(sentences[:num_sentences]), []\n",
        "            \n",
        "        # 2. Hitung matriks kemiripan kosinus antar seluruh pasangan kalimat\n",
        "        sim_matrix = cosine_similarity(tfidf_matrix, tfidf_matrix)\n",
        "        np.fill_diagonal(sim_matrix, 0)  # Hilangkan self-loop\n",
        "        \n",
        "        # 3. Konstruksi graf NetworkX berbobot kemiripan\n",
        "        nx_graph = nx.from_numpy_array(sim_matrix)\n",
        "        \n",
        "        # 4. Hitung skor sentralitas PageRank\n",
        "        try:\n",
        "            scores = nx.pagerank(nx_graph, alpha=self.damping, max_iter=self.max_iter)\n",
        "        except Exception:\n",
        "            scores = {i: float(sim_matrix[i].sum()) for i in range(len(sentences))}\n",
        "            \n",
        "        # 5. Peringkat kalimat berdasarkan skor PageRank tertinggi\n",
        "        ranked_sentences = sorted(((scores[i], i) for i in range(len(sentences))), reverse=True)\n",
        "        top_indices = sorted([idx for _, idx in ranked_sentences[:num_sentences]])\n",
        "        \n",
        "        selected_sentences = [sentences[i] for i in top_indices]\n",
        "        summary_text = ' '.join(selected_sentences)\n",
